var onboardFlags struct {
	dir   string
	force bool
}

var onboardCmd = &cobra.Command{
	Use:   "onboard",
	Short: "Generate .gitee/agent.md with AI agent workflow templates",
	Long: `Generate a .gitee/agent.md file in the current directory (or --dir)
with pre-built orchestration templates for AI coding agents.

The generated file teaches agents how to use gitee-cli effectively:
--agent-help for every command, JSON output for parsing, common
workflow patterns (issue→PR→merge→close), and authentication setup.

This follows the industry trend of putting agent instructions in
repository roots (CLAUDE.md, AGENTS.md, .cursorrules, etc.). The
gitee-cli version focuses on CLI-native agent orchestration.

If the file already exists, use --force to overwrite.`,
	Example: `  gitee agent onboard
  gitee agent onboard --dir ./my-project
  gitee agent onboard --force`,
	PreRunE: func(c *cobra.Command, args []string) error {
	rt := cmd.RuntimeFromCmd(c)
		if rt.AgentHelp {
			cmd.PrintAgentHelp(onboardAgentHelp)
		}
		return nil
	},
	RunE: runOnboard,
}

func init() {
	f := onboardCmd.Flags()
	f.StringVar(&onboardFlags.dir, "dir", ".", "Target directory (defaults to current)")
	f.BoolVar(&onboardFlags.force, "force", false, "Overwrite existing .gitee/agent.md")
}

func runOnboard(cobraCmd *cobra.Command, args []string) error {
	targetDir := onboardFlags.dir
	giteeDir := filepath.Join(targetDir, ".gitee")
	agentFile := filepath.Join(giteeDir, "agent.md")

	if !onboardFlags.force {
		if _, err := os.Stat(agentFile); err == nil {
			cyan := color.New(color.FgCyan).SprintFunc()
			fmt.Printf("%s .gitee/agent.md already exists.\n", cyan("note:"))
			fmt.Printf("  Use --force to overwrite, or edit it directly.\n")
			return nil
		}
	}

	if err := os.MkdirAll(giteeDir, 0755); err != nil {
		return fmt.Errorf("creating .gitee directory: %w", err)
	}

	if err := os.WriteFile(agentFile, []byte(agentMd), 0644); err != nil {
		return fmt.Errorf("writing .gitee/agent.md: %w", err)
	}

	green := color.New(color.FgGreen).SprintFunc()
	bold := color.New(color.Bold).SprintFunc()
	absPath, _ := filepath.Abs(agentFile)
	fmt.Printf("%s Generated %s\n", green("✓"), bold(absPath))
	fmt.Println()
	fmt.Printf("  This file teaches AI agents how to use gitee-cli effectively.\n")
	fmt.Printf("  Tip: run %s to see what your agent will see.\n", color.CyanString("cat .gitee/agent.md"))
	return nil
}

